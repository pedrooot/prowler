// Command codegen mirrors the check metadata that lives next to the Python
// checks into the Go tree: one validated bundle per provider, embedded at
// build time, plus the import barrel that links every service package in.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/prowler-cloud/prowler/prowler-go/pkg/check"
)

func main() {
	source := flag.String("source", "../prowler/providers", "root of the Python providers tree")
	out := flag.String("out", "pkg/provider", "root of the Go providers tree")
	flag.Parse()

	byProvider, err := collect(*source)
	if err != nil {
		fail(err)
	}
	if len(byProvider) == 0 {
		fail(fmt.Errorf("no metadata found under %s", *source))
	}

	providers := make([]string, 0, len(byProvider))
	for name := range byProvider {
		providers = append(providers, name)
	}
	sort.Strings(providers)

	for _, provider := range providers {
		metadata := byProvider[provider]
		sort.Slice(metadata, func(i, j int) bool { return metadata[i].CheckID < metadata[j].CheckID })
		if err := emit(*out, provider, metadata); err != nil {
			fail(err)
		}
		fmt.Printf("%-14s %4d checks %3d services\n", provider, len(metadata), countServices(metadata))
	}
}

func collect(root string) (map[string][]*check.Metadata, error) {
	byProvider := make(map[string][]*check.Metadata, 16)
	seen := make(map[string]string, 1400)

	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(d.Name(), ".metadata.json") {
			return err
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		m, err := check.UnmarshalMetadata(raw)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		key := m.Provider + "/" + m.CheckID
		if previous, dup := seen[key]; dup {
			return fmt.Errorf("check %s declared in both %s and %s", key, previous, path)
		}
		seen[key] = path
		byProvider[m.Provider] = append(byProvider[m.Provider], m)
		return nil
	})
	return byProvider, err
}

func countServices(metadata []*check.Metadata) int {
	services := make(map[string]struct{}, len(metadata))
	for _, m := range metadata {
		services[m.ServiceName] = struct{}{}
	}
	return len(services)
}

func emit(outRoot, provider string, metadata []*check.Metadata) error {
	dir := filepath.Join(outRoot, provider, "meta")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	bundle, err := json.MarshalIndent(metadata, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "metadata.json"), append(bundle, '\n'), 0o644); err != nil {
		return err
	}

	loader := fmt.Sprintf(loaderTemplate, provider, provider)
	if err := os.WriteFile(filepath.Join(dir, "meta_gen.go"), []byte(loader), 0o644); err != nil {
		return err
	}

	return emitBarrel(outRoot, provider, metadata)
}

func emitBarrel(outRoot, provider string, metadata []*check.Metadata) error {
	services := make(map[string]struct{}, len(metadata))
	for _, m := range metadata {
		services[m.ServiceName] = struct{}{}
	}
	names := make([]string, 0, len(services))
	for name := range services {
		if _, err := os.Stat(filepath.Join(outRoot, provider, "services", name)); err != nil {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/codegen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", provider)
	if len(names) > 0 {
		fmt.Fprintf(&b, "// Importing a service package runs its init, which registers its checks.\nimport (\n")
		for _, name := range names {
			fmt.Fprintf(&b, "\t_ %q\n", checkPackagePath(provider, name))
		}
		fmt.Fprintf(&b, ")\n")
	}

	dir := filepath.Join(outRoot, provider)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "checks_gen.go"), []byte(b.String()), 0o644)
}

func checkPackagePath(provider, service string) string {
	return fmt.Sprintf("github.com/prowler-cloud/prowler/prowler-go/pkg/provider/%s/services/%s", provider, service)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "codegen:", err)
	os.Exit(1)
}

const loaderTemplate = `// Code generated by internal/codegen. DO NOT EDIT.

// Package meta serves the embedded check metadata of the %s provider.
package meta

import (
	_ "embed"
	"fmt"

	"github.com/prowler-cloud/prowler/prowler-go/pkg/check"
)

//go:embed metadata.json
var bundle []byte

var byID map[string]*check.Metadata

func init() {
	all, err := check.UnmarshalBundle(bundle)
	if err != nil {
		panic(fmt.Sprintf("%s metadata bundle: ` + "%%v" + `", err))
	}
	byID = all
	bundle = nil
}

// Get returns the metadata of a check, and panics when the check ID is not
// part of the bundle, which can only happen if generated code went stale.
func Get(checkID string) *check.Metadata {
	m, ok := byID[checkID]
	if !ok {
		panic("unknown check " + checkID)
	}
	return m
}

// All returns every check metadata of the provider, keyed by check ID.
func All() map[string]*check.Metadata { return byID }
`
